import { parseRegisteredMermaid } from '../src/agent/parse.ts'
import { asFlowchart } from '../src/agent/types.ts'
import { mutate } from '../src/agent/mutate.ts'
import { serializeMermaid } from '../src/agent/serialize.ts'
import { renderAndVerifyMermaid } from '../src/agent/verify.ts'
import { editorStateHref } from '../scripts/site/editor-state-url.ts'

const SOURCE = 'flowchart LR\naccTitle: Review workflow\naccDescr: Draft flows through review to publication.\n  Draft[Draft] --> Review[Review] --> Publish[Publish]'
const OPERATION = { kind: 'set_label', target: 'Review', label: 'Approved' } as const
const escape = (value: string) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')

/** Replay real build-time API results without downloading a renderer to read docs. */
export function buildDocsEditDemo() {
  const parsed = parseRegisteredMermaid(SOURCE)
  if (!parsed.ok) throw new Error('Docs example did not parse')
  const diagram = asFlowchart(parsed.value)
  if (!diagram) throw new Error('Docs example is not a flowchart')
  const changed = mutate(diagram, OPERATION)
  if (!changed.ok) throw new Error(`Docs example mutation failed: ${changed.error.message}`)
  const afterSource = serializeMermaid(changed.value)
  const states = [SOURCE, afterSource].map((source, index) => {
    const rendered = renderAndVerifyMermaid(source, { style: ['crisp', 'paper'], security: 'strict', embedFontImport: false, idPrefix: `docs-edit-${index}-` })
    if (!rendered.verification.ok) throw new Error('Docs edit example failed verification')
    return { source, svg: rendered.svg, warnings: rendered.verification.warnings, editor: editorStateHref({ source, style: 'crisp', palette: 'paper' }) }
  })
  const html = `<section class="edit-demo" data-edit-demo aria-labelledby="edit-demo-title">
<h2 id="edit-demo-title">See one typed edit</h2>
<p>Change the review label while keeping the same three node identities and two connections. Replay the results below, generated by the real API during the site build.</p>
<pre><code>mutate(diagram, ${escape(JSON.stringify(OPERATION))})</code></pre>
<div class="edit-demo-controls" role="group" aria-label="Diagram edit example">
<button type="button" data-edit-state="0" aria-pressed="true">Before</button>
<button type="button" data-edit-state="1" aria-pressed="false">Apply typed edit</button>
</div>
${states.map((state, index) => `<div data-edit-panel="${index}"${index ? ' hidden' : ''}>
<figure><div class="plate dia-plate">${state.svg}</div><figcaption>${index ? 'After: Review is now labelled Approved. Its identity is still Review.' : 'Before: Draft flows through Review to Publish.'}</figcaption></figure>
<details><summary>Mermaid source</summary><pre><code>${escape(state.source)}</code></pre></details>
<p><a href="${escape(state.editor)}">Open ${index ? 'edited' : 'original'} diagram in the editor</a></p>
</div>`).join('\n')}
<p class="edit-demo-status" role="status" aria-live="polite" data-before-status="Original diagram verified: ${states[0]!.warnings.length} warnings." data-after-status="Edited diagram verified: ${states[1]!.warnings.length} warnings.">Original diagram verified: ${states[0]!.warnings.length} warnings.</p>
<noscript><p>Enable JavaScript to replay the edit, or open the original diagram in the editor.</p></noscript>
</section>`
  return { html, beforeSource: SOURCE, afterSource, operation: OPERATION, states }
}
