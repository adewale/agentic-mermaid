import { ui } from './context.js';
import { initialize as initializeHelpers } from './helpers.js';
import { initialize as initializeState } from './state.js';
import { initialize as initializeElements } from './elements.js';
import { initialize as initializeSharing } from './sharing.js';
import { initialize as initializeRuntimeRecovery } from './runtime-recovery.js';
import { initialize as initializeRendering } from './rendering.js';
import { initialize as initializeMotion } from './motion.js';
import { initialize as initializeZoom } from './zoom.js';
import { initialize as initializeC4Navigation } from './c4-navigation.js';
import { initialize as initializeDiagramTools } from './diagram-tools.js';
import { initialize as initializePan } from './pan.js';
import { initialize as initializeEditorHelpers } from './editor-helpers.js';
import { initialize as initializeExamples } from './examples.js';
import { initialize as initializeConfigPanel } from './config-panel.js';
import { initialize as initializeColorPicker } from './color-picker.js';
import { initialize as initializeFontPicker } from './font-picker.js';
import { initialize as initializeTabs } from './tabs.js';
import { initialize as initializeButtons } from './buttons.js';
import { initialize as initializeExport } from './export.js';
import { initialize as initializeResize } from './resize.js';
import { initialize as initializeToast } from './toast.js';
import { initialize as initializeDarkMode } from './dark-mode.js';
import { initialize as initializeInit } from './init.js';

export function startEditor(catalogs) {
  Object.assign(ui, catalogs);
  initializeHelpers();
  initializeState();
  initializeElements();
  initializeSharing();
  if (document.getElementById('runtime-recovery')) initializeRuntimeRecovery();
  initializeRendering();
  initializeMotion();
  initializeZoom();
  initializeC4Navigation();
  initializeDiagramTools();
  initializePan();
  initializeEditorHelpers();
  initializeExamples();
  initializeConfigPanel();
  initializeColorPicker();
  initializeFontPicker();
  initializeTabs();
  initializeButtons();
  initializeExport();
  initializeResize();
  initializeToast();
  initializeDarkMode();
  initializeInit();
}
